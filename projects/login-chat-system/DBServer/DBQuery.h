#pragma once
#include <cstdint>
#include <variant>

//--------------------------------------------------------------------------------------------
// DB 저장 메시지 타입
//--------------------------------------------------------------------------------------------
enum class DBQueryType : uint16_t
{
    LevelUp = 0,
    MoneyAdd = 1,
    QuestComplete = 2,
    ItemBuy = 3,
    ItemTrade = 4,  // 기존 코드에서 ItemBuy와 중복(3)이었으므로 수정
};

//--------------------------------------------------------------------------------------------
// DB 저장 메시지의 헤더
//--------------------------------------------------------------------------------------------
struct DBQueryHeader
{
    DBQueryType type{};
};

//--------------------------------------------------------------------------------------------
// 플레이어 레벨업
//--------------------------------------------------------------------------------------------
struct DBQueryLevelUp
{
    int64_t accountNo{};
    int32_t level{};
};

//--------------------------------------------------------------------------------------------
// 플레이어 돈 증가
//--------------------------------------------------------------------------------------------
struct DBQueryMoneyAdd
{
    int64_t  accountNo{};
    int32_t  money{};
    int32_t  why{};        // 사유
};

//--------------------------------------------------------------------------------------------
// 퀘스트 완료
//--------------------------------------------------------------------------------------------
struct DBQueryQuestComplete
{
    int64_t accountNo{};
    int32_t questId{};
};

//--------------------------------------------------------------------------------------------
// 아이템 구매
//--------------------------------------------------------------------------------------------
struct DBQueryItemBuy
{
    int64_t accountNo{};
    int32_t itemId{};
    int32_t price{};       // 가격이 DB에 정해져 있다면 생략 가능
    int32_t slot{};
    // 아이템마다 능력치가 고정이라면 itemId만으로 충분하나,
    // 개별 추가 능력치가 생성되는 컨텐츠라면 해당 능력치도 함께 전달 필요
};

//--------------------------------------------------------------------------------------------
// 거래
//--------------------------------------------------------------------------------------------
struct DBQueryItemTrade
{
    int64_t fromAccountNo{};
    int64_t fromItemSlot{};
    int64_t toAccountNo{};
    int64_t toItemSlot{};
    int32_t tradeMoney{};
    int32_t quantity{};
    // 인벤토리 슬롯 위치로 거래를 성사시키거나,
    // 아이템 고유 ID로 처리하는 것도 가능
};


//--------------------------------------------------------------------------------------------
// 메시지 variant (포인터 없이 값 복사로 전달)
//--------------------------------------------------------------------------------------------
using DBQueryMessage = std::variant<
    DBQueryLevelUp,
    DBQueryMoneyAdd,
    DBQueryQuestComplete,
    DBQueryItemBuy,
    DBQueryItemTrade
>;